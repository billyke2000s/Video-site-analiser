"""Offline regression for the generated archive.org adapter (native:archive_org).

Generated by Video Site Analyser from a recorded, verified run. Replays that run's HTTP exchanges
through MovieHub's real moviehub_vod.query_site(); no network is used.
"""
import json
import unittest
from pathlib import Path

import base64
import io
import re
import socket
from urllib.parse import urlsplit

import requests
from requests.structures import CaseInsensitiveDict

PLACEHOLDER_ADDRESS = "93.184.215.14"


class Replay:
    def __init__(self, entries):
        self.entries = entries
        self.requests = []

    def _find(self, method, url, start):
        best = None
        for entry in self.entries:
            if entry["method"] != method or entry["url"] != url:
                continue
            first = 0
            if entry.get("range"):
                first = int(re.match(r"bytes=(\d+)-", entry["range"]).group(1))
            body_length = len(base64.b64decode(entry["body"]))
            if first <= start < first + max(body_length, 1) or (start == 0 and first == 0):
                if best is None or first > best[1]:
                    best = (entry, first)
        return best

    def request(self, session, method, url, **kwargs):
        headers = CaseInsensitiveDict(kwargs.get("headers") or {})
        wanted = re.match(r"bytes=(\d+)-(\d*)", headers.get("Range", "") or "")
        start = int(wanted.group(1)) if wanted else 0
        self.requests.append((method, url, headers.get("Range")))
        for entry in self.entries:
            # A recorded request that was redirected: answer the original URL with the redirect.
            if entry["method"] == method and entry["url"] == url and entry.get("final_url", url) != url:
                return self._response(url, 302, {"Location": entry["final_url"]}, b"")
        found = self._find(method, url, start) or self._find_final(method, url, start)
        if found is None:
            raise AssertionError("Unrecorded request: " + method + " " + url)
        entry, first = found
        body = base64.b64decode(entry["body"])
        out_headers = dict(entry.get("headers", {}))
        status = entry["status"]
        if wanted:
            end = int(wanted.group(2)) if wanted.group(2) else None
            offset = start - first
            body = body[offset:(end - first + 1) if end is not None else None]
            total = re.search(r"/(\d+)$", out_headers.get("content-range", ""))
            size = total.group(1) if total else "*"
            out_headers["content-range"] = "bytes %d-%d/%s" % (start, start + max(len(body), 1) - 1, size)
            out_headers["content-length"] = str(len(body))
            status = 206 if status in (200, 206) else status
        return self._response(url, status, out_headers, body)

    def _find_final(self, method, url, start):
        aliases = [dict(e, url=e["final_url"]) for e in self.entries if e.get("final_url") == url]
        return Replay(aliases)._find(method, url, start) if aliases else None

    @staticmethod
    def _response(url, status, headers, body):
        response = requests.Response()
        response.status_code = status
        response.headers = CaseInsensitiveDict(headers)
        response.raw = io.BytesIO(body)
        response.url = url
        response.reason = "Replayed"
        response.encoding = "utf-8"
        return response


def install(entries):
    """Start patches for `requests` and DNS; returns (replay, patches). Stop the patches after use."""
    from unittest import mock

    replay = Replay(entries)

    def transport(session, method, url, **kwargs):
        return replay.request(session, method, url, **kwargs)

    def resolve(host, port, *args, **kwargs):
        return [(socket.AF_INET, socket.SOCK_STREAM, 6, "", (PLACEHOLDER_ADDRESS, port or 443))]

    patches = [mock.patch.object(requests.Session, "request", new=transport),
               mock.patch.object(socket, "getaddrinfo", new=resolve)]
    for item in patches:
        item.start()
    return replay, patches


def hosts(entries):
    return sorted({urlsplit(e["url"]).hostname for e in entries})


import moviehub_vod as vod
from moviehub_compat import client
from moviehub_native import archive_org

FIXTURE = json.loads((Path(__file__).resolve().parent / "vod-fixtures" / "native_archive_org.json").read_text())


class GeneratedArchiveOrgTests(unittest.TestCase):
    def setUp(self):
        self.replay, patches = install(FIXTURE["entries"])
        for item in patches:
            self.addCleanup(item.stop)

    def test_adapter_lists_every_distinct_recorded_file(self):
        client.scope(lambda: False, timeout=60, http=FIXTURE["http"])
        info = FIXTURE["info"]
        provider = archive_org.source()
        key = provider.movie(info["imdb"], info["tmdb"], info["title"], info["title"],
                             [{"title": info["title"], "country": "us"}], info["year"])
        rows = provider.sources(key, [])
        urls = sorted(row["url"].partition("|")[0] for row in rows)
        self.assertEqual(urls, sorted(FIXTURE["expected_urls"]))
        self.assertTrue(all(row["direct"] for row in rows))

    def test_moviehub_query_site_accepts_the_verified_media(self):
        result = json.loads(vod.query_site("native:archive_org", json.dumps(FIXTURE["info"]), lambda: False))
        self.assertEqual(result["status"], "complete", result)
        self.assertEqual(len(result["sources"]), FIXTURE["expected_playable"])
        for item in result["sources"]:
            self.assertEqual(item["provider"], "native:archive_org")
            self.assertGreaterEqual(item.get("durationSeconds") or 120, 120)

    def test_an_unknown_title_requests_no_detail_page(self):
        client.scope(lambda: False, timeout=60, http=FIXTURE["http"])
        provider = archive_org.source()
        key = provider.movie("", "", "Zz Title That Does Not Exist", "", [], "1900")
        try:
            rows = provider.sources(key, [])
        except AssertionError:
            rows = []  # the search request itself was not recorded: nothing was fetched beyond it
        self.assertEqual(rows, [])
        self.assertLessEqual(len(self.replay.requests), 1)


if __name__ == "__main__":
    unittest.main()
