def write_package(recipe: dict, out_dir: Path, fixture: Fixture | None) -> dict[str, Path]:
    """Write the adapter, record, test and fixture under out_dir (mirroring MovieHub's layout)."""
    validate_recipe(recipe)
    out_dir = Path(out_dir)
    paths = {
        "adapter": out_dir / "android-tv-launcher/app/src/main/python/moviehub_native" / f"{recipe['id']}.py",
        "record": out_dir / "provider_record.json",
        "recipe": out_dir / "recipe.json",
    }
    paths["adapter"].parent.mkdir(parents=True, exist_ok=True)
    paths["adapter"].write_text(render_adapter(recipe))
    paths["record"].write_text(json.dumps(provider_record(recipe), indent=2) + "\n")
    paths["recipe"].write_text(json.dumps(recipe, indent=2) + "\n")
    if fixture is not None:
        name = f"native_{recipe['id']}.json"
        paths["fixture"] = out_dir / "android-tv-launcher/tests/vod-fixtures" / name
        paths["test"] = out_dir / "android-tv-launcher/tests" / f"test_native_{recipe['id']}.py"
        paths["fixture"].parent.mkdir(parents=True, exist_ok=True)
        paths["fixture"].write_text(json.dumps(dict(info=fixture.info, http=fixture.http, entries=fixture.entries,
                                                    expected_urls=fixture.expected_urls,
                                                    expected_playable=fixture.expected_playable), indent=1))
        paths["test"].write_text(render_test(recipe, name))
    return paths
